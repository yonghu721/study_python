# print()

#方式二:解包
for id,name,yuwen,shuxue,yingyu in students:
    total = yuwen+shuxue+yingyu
    avg = total/3
    print(f"{id} \t {name} \t {yuwen} \t {shuxue} \t {yingyu} \t {avg:.2f}")
#2. 统计各科成交的最低分,最高分,平均分,并输出.
yuwen = [i[2] for i in students]
shuxue = [i[3] for i in students]
yingyu = [i[4] for i in students]
print(f"语文最高分为:{max(yuwen)},最低分为:{min(yuwen)},平均分为:{sum(yuwen)/len(yuwen):.2f}")
print(f"数学最高分为:{max(shuxue)},最低分为:{min(shuxue)},平均分为:{sum(shuxue)/len(shuxue):.2f}")
print(f"英语最高分为:{max(yingyu)},最低分为:{min(yingyu)},平均分为:{sum(yingyu)/len(yingyu):.2f}")
print()
#3. 查找成绩优秀(平均分大于90)的学生,并输出
for i in students:
    total = i[2]+i[3]+i[4]
    avg = total/3
    if avg > 90:
        print(f"学号:{i[0]},姓名:{i[1]},平均分:{avg:.2f}")
