#案例 : 根据提供的学生成绩单,完成如下需求:
    #1. 计算每个学生的总分,各科平均分,然后一并输出出来.
    #2. 统计各科成交的最低分,最高分,平均分,并输出.
    #3. 查找成绩优秀(平均分大于90)的学生,并输出

students = (
    ("S001","王林",85,92,78),
    ("S002","李慕婉",92,88,95),
    ("S003","十三",78,85,82),
    ("S004","增牛",88,79,91),
    ("S005","周铁",95,96,89),
    ("S006","王卓",76,82,77),
    ("S007","红蝶",89,91,94),
    ("S008","徐立国",75,69,82),
    ("S009","许木",86,89,98),
    ("S010","遁天",86,59,72)
)
#1. 计算每个学生的总分,各科平均分,然后一并输出出来.
#方式一
# for i in students:
#     total = i[2]+i[3]+i[4]
